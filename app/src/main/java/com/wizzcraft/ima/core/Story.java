    private static int rank(Facts f, int job) {
        return f.jobId == job ? f.jobRank : -1;
    }

    private static boolean rest(Facts f) {
        return has(f, 0) || has(f, 1);
    }

    private static int restRank(Facts f) {
        return Math.max(rank(f, 0), rank(f, 1));
    }

