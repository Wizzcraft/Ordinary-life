    // ------------------------------------------------------------------ the year

    static List<Beat> onNewDay(Facts f, Random r) {
        List<Beat> out = new ArrayList<>();
        if (f.day >= FINAL_DAY) return out;
        boolean minorTaken = false;
        for (Entry e : DAILY) {
            if (out.size() >= 2) break;
            if (f.seen(e.beat.id)) continue;
            if (!e.major && minorTaken) continue;
            if (!e.when.ok(f, r)) continue;
            out.add(e.beat);
            if (!e.major) minorTaken = true;
        }
        return out;
    }

    /** Every morning beat in priority order; for the desktop checker. */
    static List<Beat> allDaily() {
        List<Beat> out = new ArrayList<>();
        for (Entry e : DAILY) out.add(e.beat);
        return out;
    }

