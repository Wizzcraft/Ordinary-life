    // ================= street encounters =================

    private interface Cond {
        boolean ok(Facts f);
    }

    private interface Make {
        Beat make(Facts f);
    }

    private static final class Street {
        final String id;
        final Cond when;
        final Make make;

        Street(String id, Cond when, Make make) {
            this.id = id;
            this.when = when;
            this.make = make;
        }
    }

    /** Collects answers; an answer the player can't afford is simply left out. */
    private static final class Ask {
        final String id, speaker, text;
        final List<String> opts = new ArrayList<>(), replies = new ArrayList<>(), effects = new ArrayList<>();

        Ask(String id, String speaker, String text) {
            this.id = id;
            this.speaker = speaker;
            this.text = text;
        }

        Ask opt(String label, String reply, String effect) {
            if (opts.size() < 3) {
                opts.add(label);
                replies.add(reply);
                effects.add(effect);
            }
            return this;
        }

        Ask optIf(boolean c, String label, String reply, String effect) {
            return c ? opt(label, reply, effect) : this;
        }

        Beat done() {
            if (opts.size() < 2) return plain(id, speaker, text, null);
            int n = opts.size();
            String[] o = new String[n], rm = new String[n], rf = new String[n], e = new String[n];
            for (int i = 0; i < n; i++) {
                o[i] = opts.get(i);
                rm[i] = mf(replies.get(i), false);
                rf[i] = mf(replies.get(i), true);
                e[i] = effects.get(i);
            }
            return new Beat(id, speaker, mf(text, false), mf(text, true), o, rm, rf, e);
        }
    }

    private static Beat plain(String id, String speaker, String text, String effect) {
        return new Beat(id, speaker, mf(text, false), mf(text, true), null, null, null,
                effect == null || effect.isEmpty() ? null : new String[]{effect});
    }

    private static final List<Street> STREET = new ArrayList<>();

    private static void add(String id, Cond when, Make make) {
        STREET.add(new Street(id, when, make));
    }

    private static void say(String id, Cond when, String speaker, String text, String effect) {
        STREET.add(new Street(id, when, f -> plain(id, speaker, text, effect)));
    }

