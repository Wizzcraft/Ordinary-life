    /** A line as the shift ends, by how it went: score 0 = a disaster, 1 = fine, 2 = flawless. */
    static String shiftEnd(int jobId, float score, Facts f, Random r) {
        if (f == null) f = new Facts();
        if (Float.isNaN(score)) score = 1;
        int band = score < 0.7f ? 0 : score < 1.6f ? 1 : 2;
        if (jobId < 0 || jobId >= END.length) {
            return x(f, band == 0 ? "לא היום. מחר עוד הזדמנות." : band == 1 ? "המשמרת נגמרה. [הלכת|הלכת] הביתה."
                    : "משמרת מושלמת. כולם שמו לב.");
        }
        return x(f, any(r, java.util.Arrays.asList(END[jobId][band])));
    }

