    /** A line from the boss or the workplace as a shift begins (at most 60 characters). */
    static String shiftStart(int jobId, int rank, Facts f, Random r) {
        if (f == null) f = new Facts();
        if (jobId < 0 || jobId >= START.length) return x(f, "משמרת חדשה. [תעשה|תעשי] את זה טוב.");
        String[] sp = START_SPECIAL[jobId];
        // A tired or hungry player hears about it more often than not.
        if (tired(f) && pick(r, 3) > 0) return x(f, sp[3]);
        if (hungry(f) && pick(r, 3) > 0) return x(f, sp[4]);
        List<String> pool = new ArrayList<>();
        Collections.addAll(pool, START[jobId]);
        int rk = Math.max(0, Math.min(2, rank));
        pool.add(sp[rk]);
        pool.add(sp[rk]);
        if (jobId == 4 && night(f)) Collections.addAll(pool, START_NIGHT_GAS);
        return x(f, any(r, pool));
    }

