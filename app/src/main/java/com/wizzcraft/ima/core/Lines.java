    /** Ids of every street encounter, for the checker. */
    static List<String> streetIds() {
        List<String> ids = new ArrayList<>();
        for (Street s : STREET) ids.add(s.id);
        return ids;
    }

    /** Ids of the street encounters that fit this moment, for the checker. */
    static List<String> streetCandidates(Facts f) {
        List<String> ids = new ArrayList<>();
        for (Street s : STREET) if (s.when.ok(f)) ids.add(s.id);
        return ids;
    }

    /** A chance encounter on the way across town, or null if nothing fits. Unseen ones come first. */
    static Beat street(Facts f, Random r) {
        if (f == null) return null;
        List<Street> fresh = new ArrayList<>(), old = new ArrayList<>();
        for (Street s : STREET) {
            if (!s.when.ok(f)) continue;
            (f.seen(s.id) ? old : fresh).add(s);
        }
        List<Street> pool = fresh.isEmpty() ? old : fresh;
        if (pool.isEmpty()) return null;
        return pool.get(pick(r, pool.size())).make.make(f);
    }

    private static int pick(Random r, int n) {
        return r == null ? 0 : r.nextInt(n);
    }

    private static String any(Random r, List<String> pool) {
        return pool.get(pick(r, pool.size()));
    }

