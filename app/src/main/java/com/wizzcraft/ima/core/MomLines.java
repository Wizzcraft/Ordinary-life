    /** A tiny "אמא הייתה אומרת" line (at most 45 characters), or null for an unknown situation. */
    static String toast(String situation, Facts f, Random r) {
        String[] lines = toastLines(situation);
        if (lines == null) return null;
        return render(lines[r.nextInt(lines.length)], f != null && f.female, f == null ? new Facts() : f);
    }

    static String[] toastLines(String situation) {
        if (situation == null) return null;
        for (int i = 0; i < TOAST_SITUATIONS.length; i++) {
            if (TOAST_SITUATIONS[i].equals(situation)) return TOASTS[i];
        }
        return null;
    }
