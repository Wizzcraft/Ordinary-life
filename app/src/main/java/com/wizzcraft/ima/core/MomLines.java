    private static E add(String id, int weight, Cond cond, String text) {
        E e = new E(id, weight, cond, text);
        ALL.add(e);
        return e;
    }

    private static float v(Facts f, String key) {
        return f.var(key);
    }

    private static float trust(Facts f) {
        return f.vars.containsKey("mom.trust") ? f.var("mom.trust") : 50;
    }

    private static float worry(Facts f) {
        return f.vars.containsKey("mom.worry") ? f.var("mom.worry") : 50;
    }

    private static boolean visitNear(Facts f) {
        return f.day >= 92;
    }

    private static boolean newJob(Facts f, int id) {
        return f.jobId == id && v(f, "mom.job") != id + 1;
    }

    private static boolean job(Facts f, int id) {
        return f.jobId == id;
    }

