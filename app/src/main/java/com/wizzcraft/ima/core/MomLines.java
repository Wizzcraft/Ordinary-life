    /**
     * Mom's weekly call. Picks, by weight, among the beats that fit and have not been heard this run;
     * only when every fitting beat was heard does she repeat one (the all-purpose ones always fit).
     */
    static Beat weekly(Facts f, Random r) {
        List<E> fit = new ArrayList<>(), fresh = new ArrayList<>();
        for (E e : ALL) {
            if (!safe(e, f)) continue;
            fit.add(e);
            if (!f.seen(e.id)) fresh.add(e);
        }
        List<E> pool = fresh.isEmpty() ? fit : fresh;
        if (pool.isEmpty()) pool = ALL; // cannot happen: the fallbacks always fit
        int total = 0;
        for (E e : pool) total += e.weight;
        int pick = r.nextInt(Math.max(1, total));
        E chosen = pool.get(pool.size() - 1);
        for (E e : pool) {
            pick -= e.weight;
            if (pick < 0) {
                chosen = e;
                break;
            }
        }
        return build(chosen, f);
    }

    private static boolean safe(E e, Facts f) {
        try {
            return e.cond.ok(f);
        } catch (RuntimeException ex) {
            return false;
        }
    }

    /** Ids of the beats whose condition fits right now (for the checker). */
    static List<String> fittingIds(Facts f) {
        List<String> ids = new ArrayList<>();
        for (E e : ALL) if (safe(e, f)) ids.add(e.id);
        return ids;
    }

    static List<String> allIds() {
        List<String> ids = new ArrayList<>();
        for (E e : ALL) ids.add(e.id);
        return ids;
    }

    /** Every beat rendered for these facts, whether or not it fits (for the checker). */
    static List<Beat> allBeats(Facts f) {
        List<Beat> out = new ArrayList<>();
        for (E e : ALL) out.add(build(e, f));
        return out;
    }

    private static Beat build(E e, Facts f) {
        int n = e.opts.size();
        String extra = e.track == null ? null : e.track.extra(f);
        String seen = "seen." + e.id + "=1";
        String[] options = new String[n], rm = new String[n], rf = new String[n];
        String[] effects = new String[Math.max(1, n)];
        for (int i = 0; i < n; i++) {
            String[] o = e.opts.get(i);
            options[i] = o[0];
            rm[i] = render(o[1], false, f);
            rf[i] = render(o[1], true, f);
            effects[i] = join(o[2], extra, seen);
        }
        if (n == 0) effects[0] = join(null, extra, seen);
        return new Beat(e.id, SPEAKER, render(e.text, false, f), render(e.text, true, f),
                n == 0 ? null : options, n == 0 ? null : rm, n == 0 ? null : rf, effects);
    }

    private static String join(String a, String b, String c) {
        StringBuilder sb = new StringBuilder();
        for (String s : new String[]{a, b, c}) {
            if (s == null || s.isEmpty()) continue;
            if (sb.length() > 0) sb.append(';');
            sb.append(s);
        }
        return sb.toString();
    }

    /** Resolves [masc/fem], {job}, {rank} and {boxes}; leaves {name} for the dialog system. */
    static String render(String s, boolean female, Facts f) {
        StringBuilder sb = new StringBuilder(s.length());
        int i = 0;
        while (i < s.length()) {
            char c = s.charAt(i);
            int close = c == '[' ? s.indexOf(']', i) : -1;
            int slash = close > 0 ? s.indexOf('/', i) : -1;
            if (close > 0 && slash > i && slash < close) {
                sb.append(female ? s.substring(slash + 1, close) : s.substring(i + 1, slash));
                i = close + 1;
            } else {
                sb.append(c);
                i++;
            }
        }
        String out = sb.toString();
        int g = female ? 1 : 0;
        if (out.contains("{job}")) out = out.replace("{job}", f.jobId >= 0 && f.jobId < JOBS.length ? JOBS[f.jobId][g]
                : f.jobName != null && !f.jobName.isEmpty() ? f.jobName : JOBS[0][g]);
        if (out.contains("{rank}")) out = out.replace("{rank}", RANKS[Math.max(0, Math.min(2, f.jobRank))][g]);
        if (out.contains("{boxes}")) out = out.replace("{boxes}", String.valueOf(Math.max(2, (int) f.var("mom.boxes"))));
        return out;
    }

