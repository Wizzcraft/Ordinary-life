    /** Mom's one-line remark on the end-of-day summary (at most 70 characters). */
    static String summary(Facts f, Random r) {
        int total = 0;
        for (Pool p : SUMMARY) if (okPool(p, f)) total += p.weight * p.lines.length;
        int pick = r.nextInt(Math.max(1, total));
        for (Pool p : SUMMARY) {
            if (!okPool(p, f)) continue;
            int w = p.weight * p.lines.length;
            if (pick < w) return render(p.lines[pick / p.weight], f.female, f);
            pick -= w;
        }
        return render(SUMMARY[SUMMARY.length - 1].lines[0], f.female, f);
    }

    private static boolean okPool(Pool p, Facts f) {
        try {
            return p.cond.ok(f);
        } catch (RuntimeException ex) {
            return false;
        }
    }

    /** Every summary line rendered for one gender (for the checker). */
    static List<String> allSummaryLines(boolean female) {
        Facts f = new Facts();
        f.female = female;
        List<String> out = new ArrayList<>();
        for (Pool p : SUMMARY) for (String s : p.lines) out.add(render(s, female, f));
        return out;
    }

